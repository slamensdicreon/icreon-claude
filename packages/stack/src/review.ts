/**
 * Acceptance on live projects: a task counts as done only after its automated checks and its
 * Lead's review. A check that doesn't exist yet is "pending", never passed; the Lead judges the
 * result against the steps the specialist actually took, not against its summary.
 */

export interface CheckResult {
  status: 'pass' | 'fail' | 'pending';
  detail: string;
}

type StepEvent = Extract<LwEvent, { type: 'step.recorded' }>;

export interface CheckContext {
  projectId: string;
  state: ProjectState;
  library: ArtifactLibrary;
  fetch: typeof fetch;
  /** The task's own steps, oldest first: the audit trail checks read. */
  steps: StepEvent[];
  /** The task being judged; an agent's branch is launchworks/<taskId>. */
  taskId?: string;
  /** A read operation on one of the project's tool servers (never a write). */
  read(
    server: string,
    op: string,
    args: Record<string, unknown>,
  ): Promise<{ code: number; body: unknown }>;
}

export type Check = (ctx: CheckContext) => Promise<CheckResult>;

const pass = (detail: string): CheckResult => ({ status: 'pass', detail });
const failed = (problems: string[], more = 0): CheckResult => ({
  status: 'fail',
  detail: `${problems.join('; ')}${more ? `; and ${more} more` : ''}.`,
});

async function readJson(ctx: CheckContext, artifactId: string): Promise<unknown> {
  const doc = await ctx.library.read(ctx.projectId, artifactId);
  if (!doc) return null;
  try {
    return JSON.parse(doc.content) as unknown;
  } catch {
    return null;
  }
}

type Item = {
  key: string;
  name: string;
  status?: string;
  pilot?: boolean;
  attrs?: Record<string, unknown>;
};

const ok = (s: StepEvent) => s.data.resultCode < 300;
const last = (steps: StepEvent[], server: string, op: string) =>
  steps.filter((s) => s.data.toolServer === server && s.data.operation === op).at(-1);
const after = (steps: StepEvent[], a: StepEvent) => steps.slice(steps.indexOf(a) + 1);
/** Working-copy operations that change files. */
/** The branch accepted components are integrated on: what the editing host runs. */
const INTEGRATION_BRANCH = 'launchworks/integration';
/** Components that are their own full-width band (hero, header, footer) and the app's plumbing. */
const SECTION_EXEMPT =
  /^(ui|content-sdk|partial-design-dynamic-placeholder)\/|(^|\/)(HeroBanner|SiteHeader|SiteFooter|Header|Footer|Nav)[^/]*\.tsx$/i;
const CHANGES = new Set(['fs.write', 'exec.content-sdk-cli']);

/**
 * The checks that exist, by validator id; the platform pack adds its own. Everything else a plan
 * names is pending.
 */
export const CHECKS: Record<string, Check> = {
  // Built green after the last change, and that state committed.
  // Committing first and then building is as good as building first: what counts is that the
  // commit the green build ran on was pushed, and nothing changed after.
  'build.green': async ({ steps }) => {
    const build = last(steps, 'sandbox', 'exec.build');
    if (!build) return failed(['The task never ran the build']);
    if (!build.data.summary.startsWith('Build green')) return failed([build.data.summary]);
    const later = after(steps, build);
    if (later.some((s) => CHANGES.has(s.data.operation) && ok(s)))
      return failed(['Files changed after the last green build']);
    const commits = steps.filter((s) => s.data.operation === 'git.commit' && ok(s));
    const at = /nothing uncommitted, at ([0-9a-f]{7})/.exec(build.data.summary)?.[1];
    if (at && commits.some((c) => c.data.summary.includes(`(${at})`)))
      return pass(`Built green at ${at}, the commit pushed to the agent branch.`);
    if (later.some((s) => s.data.operation === 'git.commit' && ok(s)))
      return pass('Built green after the last change, and committed.');
    return failed(['The green build was not committed']);
  },

  // The component map was regenerated by the CLI (the build does it too), never hand-edited.
  'component-map.registered': async ({ steps }) => {
    const handEdited = steps.some(
      (s) => s.data.operation === 'fs.write' && /component-map/i.test(s.data.summary),
    );
    if (handEdited) return failed(['The component map was edited by hand']);
    const gen = steps.some(
      (s) =>
        ok(s) &&
        ((s.data.operation === 'exec.content-sdk-cli' && /generate-map/.test(s.data.summary)) ||
          (s.data.operation === 'exec.build' && s.data.summary.startsWith('Build green'))),
    );
    return gen
      ? pass('The component map was generated by the Content SDK CLI.')
      : failed(['The component map was never generated']);
  },

  // Pulled into the repository and validated by the Sitecore CLI.
  'serialization.replays': async ({ steps }) => {
    const pull = last(steps, 'sitecore-cli', 'ser.pull');
    const valid = last(steps, 'sitecore-cli', 'ser.validate');
    const problems = [
      pull && ok(pull) ? null : 'Items were not pulled',
      valid &&
      ok(valid) &&
      /valid/i.test(valid.data.summary) &&
      !/problems/i.test(valid.data.summary)
        ? null
        : 'Serialization was not validated clean',
    ].filter((x): x is string => Boolean(x));
    return problems.length ? failed(problems) : pass('Pulled and validated by the Sitecore CLI.');
  },

  // Production runs the reviewed commit: the integration branch's head, promoted to the default
  // branch. A default branch that never took it (still the starter) fails, though it deployed.
  'deploy.commit-matches': async ({ read }) => {
    const p = await read('hosting', 'project.read', {});
    if (p.code !== 200) return failed(['The Vercel project could not be read']);
    const deployments = (
      p.body as { deployments: { state: string; target: string; sha: string | null; id: string }[] }
    ).deployments;
    const prod = deployments.find((d) => d.target === 'production' && d.state === 'READY');
    if (!prod?.sha) return failed(['No ready production deployment with a commit']);
    const t = await read('build-repo', 'tree.read', {});
    const head = (t.body as { commit?: string | null } | null)?.commit;
    if (t.code !== 200 || !head)
      return { status: 'pending', detail: 'The build repository head could not be read.' };
    const i = await read('build-repo', 'tree.read', { ref: 'launchworks/integration' });
    const reviewed = (i.body as { commit?: string | null } | null)?.commit;
    if (i.code !== 200 || !reviewed)
      return { status: 'pending', detail: 'The integration branch head could not be read.' };
    const problems = [
      head !== reviewed
        ? `The default branch is at ${head.slice(0, 7)}, not the reviewed integration commit ${reviewed.slice(0, 7)}: promote it (build-repo.branch.promote)`
        : null,
      prod.sha !== head
        ? `Production runs ${prod.sha.slice(0, 7)}, but the default branch is at ${head.slice(0, 7)}`
        : null,
    ].filter((x): x is string => Boolean(x));
    return problems.length
      ? failed(problems)
      : pass(
          `Production runs ${head.slice(0, 7)}, the reviewed integration commit, from the default branch.`,
        );
  },

  // Platform Notes cite their sources.
  'notes.cited': async (ctx) => {
    const doc = await ctx.library.read(ctx.projectId, 'platform-notes');
    if (!doc) return failed(['No Platform Notes were written']);
    const links = new Set(doc.content.match(/https?:\/\/[^\s)>\]]+/g) ?? []);
    return links.size >= 3
      ? pass(`Platform Notes cite ${links.size} sources.`)
      : failed([
          `Platform Notes cite ${links.size} source${links.size === 1 ? '' : 's'}; at least 3 expected`,
        ]);
  },

  // Every crawled page has a path and a title; nothing silently missing.
  'inventory.complete': async (ctx) => {
    const inv = (await readJson(ctx, 'page-inventory')) as {
      pages?: { path?: string; url?: string; title?: string }[];
    } | null;
    if (!inv?.pages?.length) return failed(['The page inventory has no pages']);
    const bad = inv.pages.filter((p) => !(p.path || p.url) || !p.title).length;
    return bad
      ? failed([`${bad} of ${inv.pages.length} pages have no path or title`])
      : pass(`${inv.pages.length} pages, each with a path and a title.`);
  },

  'credentials.verified': async ({ state }) => {
    const given = Object.values(state.credentials).filter((c) => c.provided);
    const bad = given
      .filter((c) => c.ok !== true)
      .map((c) => `${c.system}: ${c.detail ?? 'not checked'}`);
    return bad.length
      ? failed(bad)
      : pass(`${given.length} credentials verified against their services.`);
  },

  // Gate 1's model contract: every page placed, every component specified, a pilot slice chosen.
  'blueprint.coverage': async (ctx) => {
    const bp = (await readJson(ctx, 'blueprint')) as {
      collections?: Record<string, Item[]>;
    } | null;
    if (!bp?.collections) return failed(['No Blueprint has been written']);
    const inv = (await readJson(ctx, 'page-inventory')) as {
      pages?: { path?: string; url?: string }[];
    } | null;
    const inScope = (c: string) => (bp.collections![c] ?? []).filter((i) => i.status !== 'drop');
    const all = (c: string) => bp.collections![c] ?? [];
    const problems: string[] = [];
    const placed = new Set(
      all('pages').map((p) => String(p.attrs?.path ?? '').replace(/\/$/, '') || '/'),
    );
    for (const p of inv?.pages ?? []) {
      const path = (p.path ?? (p.url ? new URL(p.url).pathname : '')).replace(/\/$/, '') || '/';
      if (!placed.has(path)) problems.push(`page ${path} is neither mapped nor dropped`);
    }
    const templates = new Set(all('templates').map((t) => t.key));
    for (const p of inScope('pages')) {
      const t = p.attrs?.template;
      if (t && !templates.has(String(t)))
        problems.push(`page ${p.key} uses unknown template ${String(t)}`);
    }
    const components = inScope('components');
    if (!components.length) problems.push('no components');
    if (!components.some((c) => c.pilot)) problems.push('no pilot components');
    for (const c of components) {
      const a = c.attrs ?? {};
      if (!Array.isArray(a.fields) || !a.fields.length) problems.push(`${c.key} has no fields`);
      if (!a.rendering) problems.push(`${c.key} has no rendering name`);
      const children = a.children as { max?: unknown } | undefined;
      if (children && typeof children.max !== 'number')
        problems.push(`${c.key}'s child items have no limit`);
      if (!a.queryBudget) problems.push(`${c.key} has no query budget`);
    }
    return problems.length
      ? failed(problems.slice(0, 8), Math.max(0, problems.length - 8))
      : pass(
          `${inScope('pages').length} pages, ${templates.size} templates and ${components.length} components, each with a model contract.`,
        );
  },

  // The accepted branches were integrated, and that build went live at the editing host's address.
  'editing-host.deployed': async ({ steps }) => {
    const merged = last(steps, 'sandbox', 'git.integrate');
    if (!merged || !ok(merged)) return failed([merged?.data.summary ?? 'Nothing was integrated']);
    const live = after(steps, merged).find(
      (s) =>
        s.data.toolServer === 'hosting' &&
        s.data.operation === 'deploy.status' &&
        ok(s) &&
        s.data.summary.includes('editing host'),
    );
    return live
      ? pass(`${merged.data.summary}; ${live.data.summary}.`)
      : failed(['The integrated build was not followed to READY at the editing host address']);
  },

  // Page builder can edit what the head renders: the app's Layout loads Sitecore's editing scripts.
  // Without them, each field's editing marker shows as raw JSON on the page instead of becoming
  // click-to-edit chrome.
  'head.editing-scripts': async ({ state, read }) => {
    const app = (state.buildRepo?.appPath ?? '').replace(/^\/|\/$/g, '');
    const at = (f: string) => (app ? `${app}/${f}` : f);
    const paths = [at('src/Layout.tsx'), at('src/Scripts.tsx')];
    let files: { path: string; content?: string }[] | null = null;
    let ref = '';
    for (const r of [INTEGRATION_BRANCH, undefined]) {
      const res = await read('build-repo', 'repo.read', { paths, ...(r ? { ref: r } : {}) });
      const got = (res.body as { files?: { path: string; content?: string }[] } | null)?.files;
      if (res.code === 200 && got?.[0]?.content !== undefined) {
        files = got;
        ref = r ?? 'the default branch';
        break;
      }
    }
    if (!files) return { status: 'pending', detail: `${paths[0]} could not be read.` };
    const layout = files[0]!.content!;
    const scripts = files[1]?.content ?? '';
    const direct = /<EditingScripts\b/.test(layout);
    const viaScripts = /<Scripts\b/.test(layout) && /<EditingScripts\b/.test(scripts);
    if (direct || viaScripts) return pass(`${paths[0]} loads Sitecore's editing scripts (${ref}).`);
    return failed([
      /<Scripts\b/.test(layout)
        ? `${paths[1]} on ${ref} no longer renders <EditingScripts />`
        : `${paths[0]} on ${ref} doesn't render <Scripts /> (Sitecore's <EditingScripts />)`,
      "Page builder shows each field's editing marker as raw JSON: restore it as the starter has it",
    ]);
  },

  // Every content component sits in the design system's Section: the source's container width,
  // section padding and band (tone), set per placement by a rendering parameter. Without it, every
  // section renders full width with no background and the page looks nothing like the source.
  'head.sections': async ({ state, read, taskId }) => {
    const app = (state.buildRepo?.appPath ?? '').replace(/^\/|\/$/g, '');
    const dir = `${app ? `${app}/` : ''}src/components`;
    // A port is judged on its own branch; an integration on what the editing host runs.
    let ref = taskId?.startsWith('port-') ? `launchworks/${taskId}` : INTEGRATION_BRANCH;
    let t = await read('build-repo', 'tree.read', { path: dir, ref });
    if (t.code !== 200) {
      ref = '';
      t = await read('build-repo', 'tree.read', { path: dir });
    }
    if (t.code !== 200) return { status: 'pending', detail: `${dir} could not be listed.` };
    const files = ((t.body as { entries?: string[] }).entries ?? [])
      .map((e) => e.replace(/ \d+$/, ''))
      .filter((f) => /\.tsx$/.test(f) && !/\.(props|test|stories)\.tsx$/.test(f))
      .filter((f) => !SECTION_EXEMPT.test(f.slice(dir.length + 1)));
    if (!files.length) return { status: 'pending', detail: `No components under ${dir}.` };
    const problems: string[] = [];
    for (let i = 0; i < files.length; i += 20) {
      const r = await read('build-repo', 'repo.read', {
        paths: files.slice(i, i + 20),
        ...(ref ? { ref } : {}),
      });
      for (const f of (r.body as { files?: { path: string; content?: string }[] } | null)?.files ??
        []) {
        if (f.content === undefined) continue;
        const name = f.path.slice(dir.length + 1);
        if (!/from ['"][^'"]*ui\/Section['"]/.test(f.content))
          problems.push(`${name} doesn't render inside ui/Section`);
        else if (!/tone/.test(f.content))
          problems.push(`${name} doesn't pass a tone from its rendering parameters to Section`);
      }
    }
    return problems.length
      ? failed(problems.slice(0, 10), Math.max(0, problems.length - 10))
      : pass(
          `${files.length} components render inside Section with a tone (${ref || 'default branch'}).`,
        );
  },

  // The site renders through its own host in Page builder, as read back.
  'rendering-host.set': async ({ steps }) => {
    const set = last(steps, 'sitecore-authoring', 'rendering-host.set');
    return set && ok(set)
      ? pass(set.data.summary)
      : failed([set?.data.summary ?? "The site's rendering host was never set"]);
  },

  // The head answers, and its editing endpoints exist (they refuse without the secret).
  'editing-host.responds': async ({ state, fetch }) => {
    const url = state.hosting?.url;
    if (!url) return failed(['No production URL is recorded for the head']);
    const get = async (u: string) => {
      try {
        return (await fetch(u, { redirect: 'manual', signal: AbortSignal.timeout(20_000) })).status;
      } catch {
        return 0;
      }
    };
    const home = await get(url);
    const config = await get(`${url.replace(/\/$/, '')}/api/editing/config`);
    const problems = [
      home === 0 || home >= 500 ? `${url} answered ${home || 'nothing'}` : null,
      config === 404 || config === 0 || config >= 500
        ? `/api/editing/config answered ${config || 'nothing'}`
        : null,
    ].filter((x): x is string => Boolean(x));
    return problems.length
      ? failed(problems)
      : pass(`${url} answers ${home}; /api/editing/config answers ${config}.`);
  },
};

export interface ReviewDeps {
  store: EventStore;
  projections: Projections;
  library: ArtifactLibrary;
  playbook: Playbook;
  isLive(projectId: string): Promise<boolean>;
  /** Whether a tool operation reads, writes or releases, from its server's own definition. */
  effect?(server: string, op: string): 'read' | 'write' | 'release' | null;
  /** The Lead's review with Claude; without it only the checks decide. */
  review: ((input: ReviewInput) => Promise<ReviewVerdict & { tokens: number }>) | null;
  checks?: Record<string, Check>;
  /** The playbook's platform pack, for its own checks, and how they read the project's systems. */
  platform?: {
    checks?: Record<string, PlatformCheck>;
    read(
      projectId: string,
      server: string,
      op: string,
      args: Record<string, unknown>,
    ): Promise<{ code: number; body: unknown }>;
    credential(projectId: string, credentialId: string): Promise<Record<string, string> | null>;
    /** Screenshots of a source page and its migration, judged side by side (when connected). */
    compareScreens?(projectId: string, page: ScreenPair): Promise<ScreenComparison>;
  };
  fetch?: typeof fetch;
  /** Called when a task's result is accepted (its write locks go). */
  onAccepted?: (projectId: string, taskId: string) => Promise<void>;
}

export function withReview(base: Activities, deps: ReviewDeps): Activities {
  const checks = deps.checks ?? CHECKS;
  const roles = new Map(deps.playbook.roles.map((r) => [r.role, r]));
  // A project's plan is compiled when it starts. Checks the playbook adds to a task template later
  // still apply to that project's tasks: a task is judged on the union.
  const templates = new Map(deps.playbook.plan.templates.map((t) => [t.id, t]));
  const acceptanceOf = (task: { templateId: string; acceptance: string[] }) => [
    ...new Set([...task.acceptance, ...(templates.get(task.templateId)?.acceptance ?? [])]),
  ];
  // Marked from the tool's definition, so the Lead judges what a call did, not what it's called.
  const effect = (e: StepEvent) => {
    const kind = deps.effect?.(e.data.toolServer, e.data.operation);
    return kind ? `[${kind}] ` : '';
  };
  return {
    ...base,
    async validate(req) {
      if (!(await deps.isLive(req.projectId))) return base.validate(req);
      const { task } = req;
      await deps.projections.catchUp(req.projectId);
      const state = deps.projections.get(req.projectId)!;
      const role = roles.get(task.role);
      const lead = (role?.reportsTo && roles.get(role.reportsTo)) || roles.get('chief-of-staff');
      const reviewerId = lead?.role ?? 'chief-of-staff';
      const log = await deps.store.read(req.projectId);
      const steps = log.filter(
        (e): e is StepEvent => e.type === 'step.recorded' && e.data.taskId === task.taskId,
      );
      const ctx: CheckContext = {
        projectId: req.projectId,
        state,
        library: deps.library,
        fetch: deps.fetch ?? ((...a) => fetch(...a)),
        steps,
        taskId: task.taskId,
        read: (server, op, args) =>
          deps.platform
            ? deps.platform.read(req.projectId, server, op, args)
            : Promise.resolve({ code: 404, body: { error: 'Not connected' } }),
      };
      const platform = deps.platform;
      const platformCheck = async (check: PlatformCheck): Promise<CheckResult> => {
        if (!state.intake || !platform)
          return { status: 'pending', detail: 'No platform to check.' };
        let blueprint: PlatformCheckContext['blueprint'] = null;
        try {
          const doc = await deps.library.read(req.projectId, 'blueprint');
          blueprint = doc ? JSON.parse(doc.content) : null;
        } catch {
          /* unreadable: the check sees none */
        }
        return check({
          projectId: req.projectId,
          target: state.intake.target,
          scope: { collection: task.collection, items: task.itemKeys },
          blueprint,
          read: (server, op, args) => platform.read(req.projectId, server, op, args),
          credential: (id) => platform.credential(req.projectId, id),
          compareScreens:
            platform.compareScreens && ((page) => platform.compareScreens!(req.projectId, page)),
          document: async (id) => {
            const d = await deps.library.read(req.projectId, id);
            try {
              return d ? (JSON.parse(d.content) as unknown) : null;
            } catch {
              return null;
            }
          },
        });
      };

      // 1. Automated checks.
      const results: { id: string; status: CheckResult['status']; detail: string }[] = [];
      const acceptance = acceptanceOf(task);
      for (const a of acceptance) {
        const id = a.startsWith('validator:') ? a.slice('validator:'.length) : null;
        if (!id) continue;
        const check = checks[id];
        const fromPlatform = platform?.checks?.[id];
        let r: CheckResult;
        try {
          r = check
            ? await check(ctx)
            : fromPlatform
              ? await platformCheck(fromPlatform)
              : { status: 'pending', detail: 'No automated check exists for this yet.' };
        } catch (err) {
          r = { status: 'pending', detail: `The check could not run: ${(err as Error).message}` };
        }
        results.push({ id, ...r });
      }
      const events: NewEvent[] = results.map((r) => ({
        type: 'step.recorded',
        actor: { kind: 'agent', id: reviewerId },
        subject: { kind: 'task', id: task.taskId },
        severity: r.status === 'fail' ? 'warning' : 'routine',
        data: {
          stepId: crypto.randomUUID(),
          agentId: reviewerId,
          taskId: task.taskId,
          toolServer: 'validators',
          operation: r.id,
          resultCode: r.status === 'pass' ? 200 : r.status === 'fail' ? 422 : 202,
          durationMs: 0,
          summary: r.detail,
          outcome: r.status,
        },
      }));
      const fails = results.filter((r) => r.status === 'fail');
      const pending = results.filter((r) => r.status === 'pending').map((r) => r.id);

      // 2. The Lead's review, against the audit trail.
      let verdict: { verdict: 'accept' | 'reject'; reason: string; tokens: number };
      if (fails.length) {
        verdict = {
          verdict: 'reject',
          reason: fails.map((f) => `${f.id}: ${f.detail}`).join(' '),
          tokens: 0,
        };
      } else if (deps.review && lead) {
        const trail = steps
          .slice(-120)
          .map(
            (e) =>
              `${e.ts.slice(11, 19)} ${effect(e)}${e.data.toolServer}.${e.data.operation} → ${e.data.outcome ?? e.data.resultCode}: ${e.data.summary}`,
          );
        const artifacts = log
          .filter(
            (e): e is Extract<LwEvent, { type: 'step.recorded' }> =>
              e.type === 'step.recorded' &&
              e.data.taskId === task.taskId &&
              e.data.toolServer === 'artifacts' &&
              e.data.resultCode < 300,
          )
          .map((e) => e.data.summary);
        try {
          verdict = await deps.review({
            lead: {
              name: lead.name,
              mandate: lead.mandate,
              model: lead.model.id,
              effort: lead.model.effort,
            },
            specialist: role?.name ?? task.role,
            charter: deps.playbook.manifest.charter,
            task: { title: task.title, acceptance },
            summary: req.result.summary ?? '',
            steps: trail,
            artifacts,
            checks: results,
            director: req.instructions ?? null,
            previous: log
              .filter(
                (e): e is Extract<LwEvent, { type: 'review.recorded' }> =>
                  e.type === 'review.recorded' && e.data.taskId === task.taskId,
              )
              .slice(-4)
              .map((e) => `${e.data.verdict}: ${e.data.note ?? ''}`),
            permissions: Object.entries(role?.tools ?? {}).map(
              ([server, grant]) =>
                `${server}: ${grant.ops.join(', ')}${grant.scope?.paths?.length ? ` (writes only under ${grant.scope.paths.join(', ')})` : ''}`,
            ),
          });
        } catch (err) {
          // A review that can't run doesn't hold the project up; it says so on the record.
          verdict = {
            verdict: 'accept',
            reason: `Accepted without a Lead review: the review could not run (${(err as Error).message}).`,
            tokens: 0,
          };
        }
      } else {
        verdict = {
          verdict: 'accept',
          reason: 'Checks passed; no Lead review is connected.',
          tokens: 0,
        };
      }
      const note = `${verdict.reason}${pending.length ? ` Pending, not passed: ${pending.join(', ')}.` : ''}`;
      events.push({
        type: 'review.recorded',
        actor: { kind: 'agent', id: reviewerId },
        subject: { kind: 'task', id: task.taskId },
        severity: verdict.verdict === 'reject' ? 'warning' : 'routine',
        data: {
          reviewerId,
          agentId: task.role,
          taskId: task.taskId,
          verdict: verdict.verdict,
          subject: task.title,
          note,
          tokens: verdict.tokens,
        },
      });
      await deps.store.append(req.projectId, events);
      if (verdict.verdict === 'accept') await deps.onAccepted?.(req.projectId, task.taskId);
      return verdict.verdict === 'accept'
        ? { pass: true, reason: null }
        : { pass: false, reason: verdict.reason };
    },
  };
}
